-- 给 evidence_bundles 的 metrics 一个落库的位置（O5 动作 3，见 0065）
--
-- ── 这一格此前是第三态：字段在契约里「看起来能判」，而库里【没有列】────────────
-- 契约 `evidenceBundleSchema.metrics`（可选，record<string, 有限数>）存在的理由写在
-- 它自己的注释里：门控要判 `metric:coverage >= 80` 这类条件，数值必须随包进来，
-- 否则 §23.1 的「八成审批由规则自动决定」无从谈起。而 0001 + 0002 的列清单里
-- 【没有 metrics】（实测 grep 当时零命中）——于是存在一条【能过门控而从未落盘】的数：
-- 内存对象带着 metrics 去判，判完哪都不留。回放看不到它，审阅时无法二次核对，
-- sha256 对账也覆盖不到它（对账只管 artifacts 那些文件）。
-- `docs/guides/how-to-write-a-charter.md` §3 反例 ② 第 2 点记的就是这一格。
--
-- ── 动作 3 给的两个选项里，为什么选「加列」而不是「从契约删掉」────────────────
-- 删掉 metrics 字段会连带杀死 `metric:` 判据形状（gates/evaluate.ts 的
-- metricCriteriaEvaluator 读的就是 bundle.metrics），而那是全仓【唯一】可机械判定
-- 的验收标准形状。用一个「暂时没人填」杀掉「能判的那一根独苗」，方向反了。
--
-- ── 这一列修掉什么、【不】修掉什么，说准 ────────────────────────────────────
-- 修掉的：那个数从此【只有一个家】——register() 序列化落库，回放与审阅能读回
-- 「当时门控判过的那份数」。第三态（契约有而库没有）到此终结。
-- 没修掉的：【谁来算这个数】。src 里生产 metrics 值的代码仍然 0 处（实测），
-- 那要 dispatch 的交接带包才有输入 —— 属 dispatch 接线那一格，不在本迁移的范围里。
-- 所以本列今天的正确读法是「通道铺好了，源头还没接」，不是「指标已经在了」。
--
-- ── 类型的选择：TEXT（JSON），不是数值列 ────────────────────────────────────
-- metrics 是一对多（指标名 → 数），形状本身就是 record；拆成宽表列等于给每个
-- 将来可能出现的指标名加一次迁移。NULL 与 '{}' 的分别是【要保留的】：
--   NULL = 这个包没带「指标」这个概念（契约字段缺省）；
--   '{}' = 带了但没声明任何具体指标。
-- 数值列做不到这个区分（NULL 与 0 会把第二种读成第一种），JSON 文本一次落盘保真。
ALTER TABLE evidence_bundles ADD COLUMN metrics TEXT;
