-- 心跳巡检的表达式索引（计划 Task 6.4「心跳调度不得阻塞写队列」）
--
-- ── 为什么这是第 0003 号迁移，而不是改 0001 ──────────────────────────
-- 0001 由 scripts/extract-appendix-c.mjs 从规格附录 C 机械提取（0002 文件头同一条理由），
-- 改它会让「这份 DDL 逐字取自规格」变成假话，而且老库里 0001 已标记应用、永不重跑。
-- 索引只能往后加。
--
-- ── 这条索引补的是哪一格 ────────────────────────────────────────────
-- 0001 给 events 建了两条索引：
--   idx_events_task  (task_id, created_at)
--   idx_events_action(action, created_at)
-- 心跳巡检的 SQL（src/heartbeat/patrol.ts 的 PATROL_SQL）问的是：
--   「这个 task 的最后一条【真实事件】是什么时候」，判据是 kind 非空且 <> 'HeartbeatStalled'，
--   而 kind 藏在 payload 这个 TEXT 列里，要 json_extract 才取得出来。
-- 两条既有索引【一条都覆盖不到】kind，于是那三个相关子查询对每个任务都要把该任务的
-- 【全部】事件行取出来、逐行做一次 json 解析。
--
-- 实测（10 万事件 / 50 个活跃任务，本机 node:sqlite 3.51.2，复算见 0019 §7。
-- 两个数是【同一份库】上只差这一条索引的对照，各取 9 趟中位）：
--   只有 0001 那两条索引：PATROL_SQL 一趟 413 ms
--   加上下面这一条：            0.28 ms
-- 差的不是常数，是【每任务全量 json 解析】变成【索引区间扫】。
--
-- 为什么这一条必须修，不能「记录为已知阈值偏差」：
-- patrol 跑在 Hub 主线程上，而 node:sqlite 是同步 API（integrity.worker.ts 文件头讲的是
-- 同一件事，0006 §7 也记过）。一趟 413 ms 期间【写队列、HTTP、SSE 全停】——
-- 实测并发提交 20 次写，最晚那次在 1733 ms 之后才落地；拿「空转同样时长」做对照时
-- 形状完全一致（1719 ms），⇒ 卡住写队列的不是锁也不是 WAL，就是主线程被同步查询占住。
-- 计划 Task 6.4 那句「心跳调度不得阻塞写队列」量的正是这个。0.28 ms 那一档不构成阻塞。
--
-- ── 表达式【必须】写成 CASE WHEN json_valid(...)，这不是防御性冗余 ────
-- 直接的 json_extract(payload, '$.kind') 建出来的索引有两个失效，都是实测的：
--   ① 老库里只要有一行 payload 不是合法 JSON，这条 CREATE INDEX 就报
--      "malformed JSON" 而【整个 0003 迁移失败】—— 而那种行今天写得进去
--      （events.payload 只有 NOT NULL，没有 json_valid 检查），
--      旁路 INSERT / 人工修数据 / 未来的导入工具都能留下它。
--      一个索引让【升级】在有脏行的库上做不成，是最难查的那类升级事故。
--   ② 建好之后，写一行畸形 payload 由「写入成功」变成「抛 malformed JSON」——
--      索引悄悄改了【写语义】。events 是 append-only 审计库，
--      写路径的契约不该被一条【读侧优化】改动。
-- 加上 json_valid 守卫之后：索引建得起来（脏行取值 NULL），写语义一字不变，
-- 而查询计划【没变差】—— 实测 EXPLAIN 仍是
--   SEARCH e USING COVERING INDEX idx_events_task_kind_created (task_id=? AND <expr>=?)
-- 表达式索引匹配的是【字面表达式】，所以 patrol.ts 那边的 SQL 必须用【同一个】
-- 写法才用得上这条索引。那就是 kindOf() 那个函数存在的原因：
-- 两侧写法漂移的后果是【索引静默失效】—— 测试全绿，生产退回 413 ms。
--
-- 列序为什么是 (task_id, <kind>, created_at)：
-- 巡检的每个子查询都是「给定 task_id，按 kind 过滤，取 created_at 的最大值」。
-- task_id 在前 ⇒ 等值定位；kind 在中间 ⇒ 过滤在索引内完成；
-- created_at 在末位 ⇒ max() 直接取区间边界。
-- 换一种列序 (task_id, created_at, <kind>) 实测 13 ms（不是 413，也远不是 0.28）：
-- kind 落到末位就退化成「按时间扫完再逐行判 kind」，max() 拿不到区间边界。
--
-- 【撤回】下面这句是本文件第一版写下的，已被复算证伪，按仓规留着不删：
--   「部分索引（WHERE json_extract(...) IS NOT NULL）实测【完全没用】，仍是 389 ms」
-- 部分索引【有用】，前提是索引列清单里【要有 created_at】。复算（同一份库，
-- 每臂新开连接，见 scripts/bench-recompute.mjs §1-9 那一段）：
--   (task_id, <kind>)             WHERE kind IS NOT NULL → 234.8 ms
--   (task_id, <kind>, created_at) WHERE kind IS NOT NULL →  0.28 ms
-- 当年量到 389 ms 那一发建的是【前者】—— 少了末位的 created_at，
-- max(created_at) 就得回到表里取值，于是慢的不是「部分索引」这个机制，
-- 是我给它挑的列清单。原来的结论把【一次列序选择错误】记成了【一种索引类型无效】，
-- 下一个人看到这句会直接跳过整条部分索引的路。
--
-- 那 0003 为什么仍然选【非部分】那一份？先撤回一条写错的理由，再给剩下的那条。
--
-- 【撤回】本文件第一版的理由①原文：
--   「计划覆盖面：非部分那份 4 个子查询探测【全部】走它；部分索引那份只有
--     两个 = 谓词的探测走它」
-- 复算（scripts/bench-recompute.mjs §1-9 三档 + 逐条 EXPLAIN，
-- 门禁在 test/heartbeat/patrol.test.ts ⑤ 那条 3/4）：
--   非部分 (task, kind, created_at)              → 3/4
--   部分   (task, kind, created_at) WHERE 非空   → 3/4
--   部分   (task, kind)             WHERE 非空   → 2/4
-- 所以「全部 vs 两个」那次对比比的【是两件事】：非部分那份【有】created_at，
-- 部分那份【没有】。一次差两个变量的对照，正是 §1 第 13 条（0019）立规矩时
-- 要拦的形状，而这次栽的是我自己刚写完那条规矩的文件头。
-- 等列清单之下，部分与非部分的覆盖面【相同】，覆盖面这条理由不成立。
--
-- 顺带把「第四个探测为什么不走它」钉清楚，否则下一个人会以为那是漏配：
-- 不走它的是 last_real_event_at 那一发，它的 kind 判据是
-- `IS NOT NULL AND <> 'HeartbeatStalled'`，【没有等值取值】可比 (task_id, <kind>=?) 那样定位，
-- 于是优化器选 idx_events_task(task_id, created_at)。这不是退化：那条索引让
-- max(created_at) 天然有序，从最新往旧走、撞到第一条满足 kind 判据的行就停。
-- 这句解释的分量在这里 —— 它是一个【有对照的测量】支持的解释，不是一次观察：
-- 同一份库、同样行数、同样 created_at 分布、同一组索引，只差【尾部那批的 kind】，
-- 尾部是真实事件 0.079 ms / 尾部是心跳事件 2.186 ms（本机 400+400 行那一档，
-- patrol.test.ts ⑤ 那条用例复现它；425 ms 那种「索引全没配上」的形状下两侧会同量级）。
-- 也就是说：如果哪天有人「顺手」把这第四格也掰到这条索引上，得先回答
-- 「那尾部全是心跳事件的任务怎么办」—— 那正是巡检自己写的事件唯一能影响性能的路径。
--
-- 换过去没有覆盖面收益、只有多一个失效面，理由剩一条：
--   部分索引的 WHERE 谓词本身也要与查询里的写法对上才生效，
--   于是多了一处【必须逐字同源】的地方（本文件下面已经为 kindOf 记过一次这个坑），
--   少一个这种约束就少一次静默失效的机会。
-- 结论没变（仍选非部分），但它是【一条】理由支持的，不是两条。
--
-- ── 代价，量过之后写在这儿 ──────────────────────────────────────────
-- 多一条索引 = 每次 INSERT 多维护一份 B 树。实测批量写 2000 行（同一台机器、同一份库、
-- 只改这一条索引、三档交替，脚本每次把【逐轮原始值】打出来）：
--   有这条索引 ~180-210 ms / 没有 ~120-180 ms ⇒ 【几十个百分点】
-- ⚠ 这里【不写单个百分比】，因为本轮发现它写不得：同一个量在仓库里曾同时存在
--   三个数（本文件头的 +19%、0019 §1 第 9 条的 +18%、脚本打印的 +35%~+43%），
--   而复算时它三次运行打出 +20% / +35% / +43%，另配一组库大小梯度打出 +6% / +18% / +93%。
--   那不是「数错了」，是【这个指标的方差比样本数大】—— 三个数的中位数不是收敛的估计。
--   稳的是两件事：① 方向 —— 这条索引确实让每次 INSERT 多写一份 B 树，代价不为零；
--   ② 量级 —— 几十个百分点，不是零也不是一倍以上。引用「+18%」会让人以为
--   可以再优化掉一半，而实际它可能本来就是噪声。复算：scripts/bench-recompute.mjs §1-9 写侧那段。
-- 同一轮里 FTS 单条查询 0.42 vs 0.48 ms ⇒ 这条索引【不影响】检索侧，
-- 它买到的全在巡检那一格（摘掉索引 413 ms → 有索引 0.28 ms，10 万事件 / 50 任务那一档）。
-- 这笔账划得来的理由不是「百分比很小」，而是【两边失效方向不同】：
-- 写侧多花几十毫秒是延迟，没人会因此丢数据；
-- 读侧那 413 ms 冻结主线程期间，Hub 上【所有】在途请求一起停。
-- events 是 append-only 审计库（0001 的 events_no_update / events_no_delete 触发器），
-- 写路径本来就只在事务尾部 fsync 一次，多一次 B 树插入落在同一个事务里。
--
-- 不含 PRAGMA：连接级设置归 src/db/pragmas.ts（test/db/migrate.test.ts 有守卫拦这个）。
-- 只用 CREATE INDEX，不 DROP / RENAME / ALTER：与 0002 文件头那条立场一致 ——
-- 审计库里任何「删掉一个查询路径」的操作都会让历史回放指向不存在的东西。

CREATE INDEX idx_events_task_kind_created
  ON events(task_id, CASE WHEN json_valid(payload) THEN json_extract(payload, '$.kind') END, created_at);
