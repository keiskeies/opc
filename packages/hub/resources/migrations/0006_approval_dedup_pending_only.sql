-- 把审批卡片的去重键收窄到【待批】那一批（O4，见 0061）
--
-- ── 这一发改的是【约束的形状】，不是数据 ────────────────────────────
-- 0004 那条索引写的是：
--
--   CREATE UNIQUE INDEX idx_approvals_card_identity
--     ON approvals(task_id, card_key) WHERE card_key IS NOT NULL;
--
-- 而 0004 自己的文件头（第 48 行）把这条索引要兑现的性质写成：
--   「判据落在 DDL 上之后，『同一个决定只有最多一张待批卡』是一条**性质**，不是一条**约定**」
--
-- 性质里有【待批】这一维，索引里没有。差的这一维不是文字疏忽，它是一条真实的死路，
-- 而 0061 拿真代码量过它的形状（下面那段是实测读数，不是推演）：
--
--   一条任务停在 IN_REVIEW/director，产出方 dev 与审阅者同模型家族 ⇒ 门 3 拦，
--   建一张 card_key = "same-family-review:dev->director" 的豁免卡。CEO 按【退回】
--   （reject_with_comment，HUMAN_EDGES 里 reject 没有出边 ⇒ 任务原地）之后：
--     · 卡片那一行变成 status='rejected'，而【它的键还在】；
--     · 下一轮 dispatch 判同族仍然拦 ⇒ 去建同一张键的卡 ⇒ 撞唯一索引
--       ⇒ insertCard 返回 skipped="duplicate" ⇒ 【一张卡都不建】；
--     · 于是 pendingCards = 0，收件箱里没有任何东西可点；
--     · 而 planEdge 那句话仍然写着「（已建卡）」；
--     · events 每轮 +3 行，IN_REVIEW ∈ DRIVER_ELIGIBLE_STATES ⇒ 驱动器每个心跳
--       自动重跑，直到那一格的尝试上限。
--   ⇒ 「CEO 说了不」被实现成「这个问题永远不再被问」，
--     而唯一的出路是手工 UPDATE approvals。
--
-- ── 为什么收窄而不是给键加轮次 ──────────────────────────────────────
-- 另一条改法是把键拼成 "…:round-2"。它挡得住这一格，但它把【判据】那一侧改坏了：
-- engine/runtime.ts 的 CEO_APPROVED_SQL 是按 (task_id, card_key) 【精确匹配】读
-- 「这件事CEO批过没有」的，键一旦带轮次，第 1 轮批的那张豁免就匹配不上第 2 轮的键，
-- 于是要么改成前缀匹配（= 把"哪一轮的批准算数"这件事交给 LIKE 的语义），
-- 要么每次退回都换键而批准永远追不上。收窄索引不动判据那一侧：它仍然精确匹配。
--
-- 也不是"退回就把任务推进一格"。规格 §7.1 没有给 reject 那条出边，
-- 而 HUMAN_EDGES 只有 approve 一条出边这件事已经登记为【规格缺口】而不是本地取舍
-- （那张表在 engine/dispatch.ts，"只有 approve 能推进"那句写在 engine/approve.ts 文件头），
-- 补一条边是把规格没给的跃迁写进状态机。
--
-- ── 为什么 DROP INDEX 不违反 0004 那条「不 DROP / RENAME / ALTER」立场 ──
-- 0004 原话是「审计库里任何『删掉一个查询路径』的操作都会让历史回放指向不存在的东西」。
-- 那条立场管的是【数据与读法】：删列、改列义、把某张历史表挪走。
-- 索引不是数据，也不是一条读法 —— 它是【写侧的约束】。删掉它：
--   · 一行都没删、一列都没改 ⇒ 历史回放读到的行【逐字不变】；
--   · 收窄是【放宽】唯一性 ⇒ 存量数据不可能因此违反新约束（旧约束是新约束的子集），
--     所以这条迁移不需要 0004 那种"存量会不会撞"的核对，也不可能撞；
--   · 被去掉的是"一个键上第二行插不进去"这条【未来的】拒绝，而不是任何【已有的】事实。
-- 也就是说这是本仓唯一一种"向后"的迁移在语义上仍然是安全的方向：它让库能表达
-- 一个此前不能表达的状态（同一决定上有过一张已退回的卡 + 一张新的待批卡），
-- 而那个状态正是这一发改动要的。
--
-- ── 收窄之后谁还在挡"白花钱" ────────────────────────────────────────
-- serve/charter-pump.ts 那道省 token 的候选筛（CHARTER_CANDIDATES_SQL 里的
-- NOT EXISTS，以及同一形状的那两处）查的是【任何状态】的卡，
-- 它【不依赖】这条索引 —— 所以"卡已批掉而任务没推进 ⇒ 不起子进程"那条性质
-- （charter-pump.test.ts 钉着的）在本迁移之后【照旧成立】，靠的是泵自己的那道筛。
-- ⚠ 这句话必须写在这里而不是只写在测试注释里：本迁移把索引从"挡一切"改成"挡 pending"，
-- 如果有人顺手把泵那道筛也改成只查 pending，"卡被批掉而任务没推进"那一格就会变成
-- 【起子进程烧一轮 token 而换回一张重复卡】。那道筛与这条索引现在是【两件事】，
-- 而它们的形状【不该】再被读成同一件事（0004 文件头那句"判据必须与 DDL 的约束
-- 同一个形状"在本迁移之后只对【待批】那一半成立，另一半是泵自己的策略）。
--
-- 不含 PRAGMA：连接级设置归 src/db/pragmas.ts（test/db/migrate.test.ts 有守卫拦这个）。

DROP INDEX IF EXISTS idx_approvals_card_identity;

-- 名字沿用 0004 那一个：读侧没有任何一条 SQL 按索引名查东西（实测全仓只有
-- 这条 DDL 与三处注释提到它），保留同名是为了【不制造第二个名字】——
-- 一条约束有两个名字的时候，下一个人不知道哪条还活着。
CREATE UNIQUE INDEX idx_approvals_card_identity
  ON approvals(task_id, card_key)
  WHERE card_key IS NOT NULL AND status = 'pending';
