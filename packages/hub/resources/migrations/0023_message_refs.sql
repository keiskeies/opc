-- 0023_message_refs.sql —— messages 补一列 ref_id：卡片消息指向它的实体
--
-- =====================================================================
-- 为什么补这一列
-- =====================================================================
-- messages.kind 里有三种卡片消息：meeting_card / backlog_card / doc_card。
-- 它们和纯文本消息的区别不只是"长得不一样"，而是"这条消息背后有一个实体"：
-- 会议卡片背后是 meetings 里的一行，待办卡片背后是 backlog_items 里的一行，
-- 文档卡片背后是 documents 里的一行。前端渲染卡片、点击卡片跳转实体详情页，
-- 都需要拿到那个实体的 id。
--
-- 0015 里没有地方放这个 id。reply_to 表达的是引用嵌套（"这条消息回复哪条
-- 消息"），指向的仍是 messages 自己，语义完全不同，硬塞会把两种关系搅成一团
-- ——以后想查"这条消息回复了谁"就会查出卡片指向的会议 id，这类混用是最难
-- 清理的债。所以补一列。
--
-- =====================================================================
-- 为什么可以随便 NULL：nullable 不是偷懒，是这一列的本性
-- =====================================================================
-- messages 表里占绝对多数的是 kind='text' 的正文和 kind='system' 的系统消息，
-- 它们背后没有实体，ref_id 对它们就是"不存在"，不是"暂时没填"。
-- 若强行 NOT NULL，每张非卡片消息都要编一个假指向或空串占位——空串在
-- join 时是无声的炸弹（join 不上不报错，只是悄悄少行）。SQLite 对
-- ALTER TABLE ADD COLUMN 也另有硬约束：NOT NULL 的新列必须带常量默认值
-- （见 0022 头注同段），TEXT 能给的常量默认值只有 ''，正好落进上面那个
-- 坑。nullable 同时躲开了语义坑和语法坑。
--
-- =====================================================================
-- 为什么是一列，不是三列：这是同一个问题的三种答案，不是三个问题
-- =====================================================================
-- 直觉上"三种卡片"配三列（meeting_id / backlog_id / doc_id）很自然，但那是
-- 把列当成类型分支用的表设计反模式：三列永远恰好只有一列非空（互斥约束要靠
-- 手写 CHECK 三选一才守得住），以后每加一种卡片就加一列，表宽随业务线性膨胀，
-- 而查询永远是 "WHERE meeting_id IS NOT NULL OR backlog_id IS NOT NULL OR
-- doc_id IS NOT NULL"——代码读到那里，列的区分价值已经没了。
-- 三张卡片问的其实是同一个问题："这条消息指向哪个实体？"。一个问题的答案
-- 就放一列，答案的种类由 kind 判别（kind 本来就是这条消息"是什么"的判别式，
-- 再拿它判别"指向谁"是同一条信息用到底）。以后加第 N 种卡片，DDL 一个字不改。
--
-- =====================================================================
-- 为什么不建外键：一列三个爹，REFERENCES 只写得出一个
-- =====================================================================
-- ref_id 的父表由 kind 决定，有三个候选：meeting_card→meetings、
-- backlog_card→backlog_items、doc_card→documents。REFERENCES 子句只允许
-- 点名一张父表。硬写 REFERENCES meetings，但 backlog_card 的消息插进来，
-- 外键检查会在 FK 开启的库上把完全合法的数据拒掉；不写 REFERENCES 却指望
-- 它按 kind 自动选表，SQLite 没这个能力。这不是 SQLite 的限制可以绕——
-- "多态指向"在关系模型里本来就没有外键表达。
-- 完整性由服务层兜：conversations/service.ts 的 insertCardMessage 插卡前
-- 先查 kind 对应的父表里 ref_id 那一行是否存在，不存在就拒（卡片消息是
-- 服务端自己生成的，没有"外部脏数据绕过检查"的入口，服务层判据够用）。
--
-- =====================================================================
-- 为什么不加 CHECK：约束管"形状"，"存在性"归服务层
-- =====================================================================
-- 考虑过加这样的 CHECK，最终没加：
--   CHECK (ref_id IS NULL OR (kind <> 'text' AND kind <> 'system'))
-- 它只否掉了半边（文本/系统消息不许带 ref_id），正半句"卡片必须带 ref_id"
-- 它写不出更该有的版本——CHECK 只能检查本行列值，证明不了 ref_id 指向的
-- 实体真的存在，也就是说这道约束最要紧的那半截它根本守不住，守得住的半截
-- 服务层判据（kind 与 ref_id 成对出现，缺一边就拒）同样守住，而且报错是
-- 带 reason 的服务错误对象，不是裸 SQLITE_CONSTRAINT_CHECK，调用方不用
-- 拆 SQLite 错误码才知道自己错在哪。
-- 另一个更实际的原因：0015 建表时 messages 没写 CHECK kind IN (...)，kind
-- 的取值域本来就只由 contracts 的 messageViewSchema 把门。单给 ref_id 配
-- 一道比 kind 本身还严的 CHECK，列与列的约束强度就对不齐了。
--
-- =====================================================================
-- 为什么另起 0023，而不是回去改 0015
-- =====================================================================
-- 迁移是 append-only 的：schema_migrations 里登记过的版本号永远不会重跑。
-- 直接改 0015 的文件体，已跑过 0015 的老库看到的还是旧 DDL（不会重放），
-- 新库看到的却是带 ref_id 的新 DDL——同一个版本号在两种库里长出两套 schema，
-- 版本对得上、列对不上，是所有分叉里最难查的一种。补列必须走新版本号，
-- 让新老库都各自执行一次"补这一列"。
-- ALTER TABLE ADD COLUMN 是纯元数据操作：不重写表、不重建索引，对现有
-- messages 行和 messages_fts 的触发器都无感，老行自动取 NULL。
ALTER TABLE messages ADD COLUMN ref_id TEXT;
