-- 卡片投递台账：让「这张卡送过没有」在库里有一个答案（O12 动作 4 的前置）
--
-- ── 这一格缺的是什么 ────────────────────────────────────────────────
-- 发卡那一路（`channels/abstraction.ts` 的 `deliverCard`）从写下那天起在 src 里
-- 【零生产调用方】。它一直没接，不是因为难，是因为接它之前必须先回答一个问题：
--     一张 pending 卡送到哪条通道、**送过没有**？
-- 后一半今天无处可答：库里没有任何一张表记着「这一张卡被推出去过」。而没有这张表
-- 就没人能安全地接上发卡 —— 每轮心跳扫一遍 pending 就每轮重发，等于每 60 秒给
-- 审批人推一张重复卡。那比不推更坏：它把人训练成忽略这张卡，而这张卡是【规格】
-- §11 那条「移动端只做决定」的唯一载体。
-- ⇒ 优化设计文档 O12 动作 4 原话：「动作 4 的前置是『投递台账』那一格
--   （含它的迁移与幂等键），不是『多调一次 send()』」。本文件就是那一格。
--
-- ── 这张表【不能】回答什么：到没到人手里 ──────────────────────────────
-- ⚠ 这一节在本轮改过一次，而改的原因值得留着：文件头最早写的是「这张表只有成功的行，
-- 失败的尝试没有行」。写那句话的时候我还没有定投递的顺序。定下来是**先抢台账再发**
-- （理由见 channels/deliver.ts 文件头那条不对称：重复卡伤的是人对系统的信任、改不回来，
-- 而「有行而没送到」是一句能查出来并能人工重推的话），于是形状变成相反的样子：
--     成功 ⇒ 有行；发送失败 ⇒ 【也有行】（那一行不回滚，回滚就等于下一轮再推一次）。
-- 所以这一张表读得出「我们抢过这一对」，读不出「审批人收到没有」——
-- 那两种情况**在这张表里长得一模一样**。这不是疏忽，是那条顺序取舍的另一面，代价写在下面：
--   · 换来的：写侧只有一条语句，没有状态列，于是没有状态机可以漂。
--     「要不要再推」的判据就退化成一句「有没有这一行」—— 一句 SQL 答得完的判据
--     才不会被下一个人写出两种理解。
--   · 代价：排障时「这张卡真到了」与「这张卡试了一次就没成」在库里分不开。
--     那一格只有**日志**答：`runDeliverPass` 把每一次失败都交成一条 note，
--     装配层把它抬成 warn（`summarizeDeliver`，同一句去重的口径在 `serve/im-channels.ts`）。
--     ⚠ 日志不是台账，它跨不过重启 —— 这是这张表**已知**的射程边界，登记在
--     O12 动作 4 与本轮台账里，别让「有台账」这句话把它读没了。
--   · 因此**故意**留了一个显式的出口：`clearDeliveriesFor` 删掉那一行 = 声明
--     「确实送出去了而没人收到，当新卡再推一次」。它不接任何自动路径（不接「N 小时
--     没批就重推」），因为那个自动化造出的正是这张表要防的事。
--
-- ── 为什么主键是 (approval_id, channel_id) 而不是加一个自增 id ──────
-- 这个组合就是**幂等键本身**，不是「顺便建的一个索引」。区别在于谁来拒绝重复：
--   · 应用层「先 SELECT 再 INSERT」⇒ 两个人（或两轮心跳）都查到没有 ⇒ 都插进去 ⇒
--     审批人收到两张卡，而库里那两行都写着「我送过」。这正是 0024 卡片去重
--     与 0025 唯一写入者反复治的那个窗口：**先查再插的判据不是判据**。
--   · 主键 ⇒ 重复的那一次 INSERT 当场失败。`runDeliverPass` 拿 `changes()` 数
--     真正落地的那几次，所以「没抢到」在读侧是一个数，不是一种猜测。
-- 不加自增 id 是因为这一张表没有任何「一行投递事件」的身份需要引用 ——
-- 它记的是**关系**（这张卡在这条通道上出现过），不是**事件**。
-- 真要有那一天，那张表叫 events，它已经有 11 种 action 与一条 append-only 判据。
--
-- ── 为什么 approval_id 带外键，且【不带】CASCADE ────────────────────
-- 带外键：这张表存在的意义是「这句话关于库里那张卡」。指向一张不存在的卡的投递行
-- 是一句**没有主语的真话**，而它比一句假话更难查（它逐字段看都是对的）。
-- 0002–0008 那几份迁移一条外键都没写，理由各自成立（它们都是在【已有表】上加列
-- 或加触发器，SQLite 不支持 ALTER TABLE ADD CONSTRAINT）；本文件是**新建表**，
-- 外键在这里是**声明**而不是补丁，不需要重建任何存量表。
-- 不带 CASCADE：删掉一张送过的卡如果顺手把台账一起清掉，那么被清掉的正好是
-- 「我们把它推给过 CEO」这唯一那份证据 —— 而这张表存在的全部理由就是留住这句话。
-- 所以删卡**当场失败**（外键约束），要删得先删台账那一行，而那次删是显式的、
-- 看得见自己在抹什么的。代价说清楚：`DELETE FROM approvals` 对送过的卡从此不再
-- 一句就走通。src 里今天【没有】任何一处删 approvals（实测：`DELETE FROM approvals`
-- 在 src 只出现在一句注释里），所以这个代价今天落在**手工改库**的人身上，
-- 而那个人正应该被拦一下。
--
-- ── action_return 存的是什么，为什么要存 ────────────────────────────
-- 那张卡推出去的那一刻**能不能在这条通道上被点**（`deliverCard` 读
-- `Channel.supportsActionReturn` 为假时会挂上 `ACTION_RETURN_HINT` 并以只读形态出去）。
-- 存这一格不是留个好看的元数据：排障时「CEO 说他手机上那张卡点不动」这句指控，
-- 唯一的辩解证据就是「它推出去的时候就是只读的，因为那一刻两条回传路都没通」。
-- 不存的话，那一刻的证据在下一轮心跳之后就**永远拿不回来了** —— `supportsActionReturn`
-- 是一个 getter，读的是通道**此刻**的健康位，它不记得自己一小时前是什么。
-- ⚠ 它记的是【推出去那一刻】的判定，不是【现在】的。卡片后来变不变可点，
-- 由卡片自己与审批人那侧决定，不归这张表说。
--
-- ── 老库上的作用 ────────────────────────────────────────────────────
-- 新建表，对存量行为零作用；存量库里这张表是空的，这是【事实正确】的空：
-- 发卡那一路从来没有生产调用方，所以历史上确实一张卡也没推出去过。
-- 这一点很值钱 —— 有些新列需要编一个值回填（0004 / 0008 为了不做这件事把列做成可空），
-- 这一张表连编都不用编。
CREATE TABLE card_deliveries (
  approval_id TEXT NOT NULL REFERENCES approvals(id),
  channel_id TEXT NOT NULL,
  sent_at INTEGER NOT NULL,
  action_return INTEGER NOT NULL,
  PRIMARY KEY (approval_id, channel_id)
);
