-- 给 approvals 一个指向【证据包】的落库位置（O5 动作 4）
--
-- ── 这一格此前是第三态：卡片要求证据，而「有没有证据」无处可答 ─────────
-- 【规格】§9.2 卡片三行的第三行是「证据链接（点开是完整证据包）」，
-- 契约 `approvalCardDraftSchema.evidence_refs`（contracts/src/gates.ts:68）
-- 把它写成必填数组。而 approvals 表的列清单里【没有任何一列存放它】——
-- evidence_refs 只活在 ApprovalRequired 事件的 payload 里，卡片自己的行上没有。
-- 于是「这张卡背后有没有证据包、指向哪里」这个问题：
--   · GET /approvals 答不了（APPROVAL_COLUMNS 没有这一列）；
--   · 收件箱 UI 答不了（approvalCard() 拿不到数据，渲染不出「无证据包」这一格）。
-- channels/abstraction.ts 自己有一句承认：「evidenceRefs 可空，原因是缺陷不是设计」。
-- 这一列补的是【存在哪里】，不是【谁来填】——
-- 生产者（dispatch 交接带包）与验包方（verify）仍是 O5 动作 1 / 2 的活；
-- 但卡片行上【有一列】之后，「这张卡没带证据」就从"无处可说"变成
-- 「这一列是 NULL / []，UI 明说『无证据包』」，后者才是可核对的状态。
--
-- ── 为什么存 JSON 文本而不是一张关联表 ───────────────────────────────
-- evidence_refs 的形状是字符串数组（`z.array(z.string().min(1)).min(1)`），
-- 一张卡对多个引用，引用的目标可以不是 evidence_bundles.id（规格允许
-- 文件路径 / 外部链接作依据，见 contracts/src/evidence.ts 的 artifactSchema）。
-- 拆成关联表会给一张 append-only 审计卡凭空加一个需要 JOIN 的中间层，
-- 而本仓对这种"读侧绕过 JSON"的代价已经量过一次（O3 动作 3 的 680ms 记录）；
-- 这里的方向相反：这一列【只在列表接口带出条数/引用】，不参与任何按证据的过滤，
-- 所以 JSON 是够用的。NULL 与 '[]' 的分别【不保留】：两者都读作「无证据包」——
-- 但契约强制 min(1)，所以正常建卡路径下这一列【要么 NULL（建卡方没传）要么
-- 非空数组】；NULL 只在老库（0008 之前建的卡，今天 0 张，0013 §10.1）上出现。
--
-- ── 可空是刻意的，与 0004 的 created_at 同一条理由 ──────────────────
-- 0008 之前建的卡【没有】这一格的历史答案。编一个（空数组？假引用？）会让
-- 「这张卡带没带证据」在存量行上永远说谎。NULL ⇒ 读侧拿到 null 时【不显示】证据行，
-- 而不是显示一个假证据。这也是 append-only 审计库的规则：新列只对【新行】生效，
-- 存量行保持「它当时没有这一格」这一事实。
ALTER TABLE approvals ADD COLUMN evidence_refs TEXT;
