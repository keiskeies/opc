-- 审批卡片的创建路径所需的一列 + 一条去重索引（0026）
--
-- ── 为什么这是第 0004 号迁移，而不是改 0001 ──────────────────────────
-- 0001 由 scripts/extract-appendix-c.mjs 从规格附录 C 机械提取（0002 / 0003 文件头
-- 同一条理由），改它会让「这份 DDL 逐字取自规格」变成假话；而 approvals 在老库里
-- 【已经存在】，改 0001 对已部署的库零作用。扩展只能往后加。
--
-- ── 这一列补的是哪一格 ──────────────────────────────────────────────
-- 0013 §10.1 实测：src 里【没有任何一条 INSERT INTO approvals】，唯一的两处写是
-- UPDATE（http/real-deps.ts 的 CLAIM_APPROVAL_SQL、policy/auto-approve.ts 的
-- CLAIM_APPROVAL_FOR_AUTO_SQL），而 UPDATE 不创建行。于是那一整条读侧
-- （POST /approvals/:id、countSimilarApprovals、role-memory 的战略档判据）
-- 建在一片【只有夹具往里写】的表上。补创建路径（src/approvals/cards.ts）时，
-- 表里缺一个能表达「这张卡代表哪一个决定」的位置：
--   · 拿 id 去重 ⇒ 每次调用都是新 id，去不了重；
--   · 拿 summary 去重 ⇒ 同一类决定（同一句话）被合成一张卡，而合并比重复贵得多
--     —— 重复是吵，合并是【吞掉一个决定且不留痕迹】；
--   · 拿 (task_id, approval_type) 去重 ⇒ 一个任务上两类审批各只能有一张，
--     第二个不可逆动作建不出卡（§8.3 明确允许同任务多次升级）。
-- 所以是一列**由建卡方 supplied 的稳定身份**，本模块不猜它的值（猜 = 替调用方
-- 决定「哪两次是同一个决定」，那是建卡方才知道的信息）。
ALTER TABLE approvals ADD COLUMN card_key TEXT;

-- ── 第二列：卡片是【什么时候】建出来的 ──────────────────────────────
-- 0001 给 approvals 的十三列里【没有任何一个创建时刻】：有 decided_at（决定时刻）、
-- 有 timeout_at（到期时刻），而「这张卡挂了多久」问的那个起点从来没有落过库。
-- 后果不是「少显示一个时间」：
--   · GET /approvals 的排序没有稳定依据（收件箱要「最老的在最上面」，
--     否则一张等了 3 天的卡会出现在列表最底部，而它正是最该被看到的那一张）；
--   · 【规格】§9.2 第二行要显示的「超时行为」只剩一个绝对到期时刻，
--     算不出「还剩多久」，也就算不出「已经过期多久」；
--   · 唯一还能推出创建时刻的地方是 events 里那条 ApprovalRequired 的 created_at，
--     于是每个列表读法都要去 join 一次 append-only 大表 —— 而卡片行与事件行
--     本来就该是同一件事的两个投影，它们的时间【必须】同源。
-- 所以补在卡片自己身上，而不是让读侧去 join。
--
-- ⚠ 这一列**可空**，而且是刻意的：0004 之前建的卡（今天生产里是 0 张，0013 §10.1）
-- 没有办法回填出真实创建时刻，**编一个**（拿 decided_at？拿 0？）会让
-- 「等了多久」这一格在存量行上永远说谎。可空 ⇒ 读侧拿到 null 时【不显示】年龄，
-- 而不是显示一个假年龄。
ALTER TABLE approvals ADD COLUMN created_at INTEGER;

-- ── 为什么去重必须是索引，而不是「建之前先查一次」 ──────────────────
-- 先查后插留着一个「都查到没有 ⇒ 都插进去」的窗口。WriteQueue 把事务串行化，
-- 所以走同一条队列的两个建卡方今天撞不上；但那条依赖是【运行期装配】给的，
-- 不是数据库给的：0025 §2 实测「第二个 WriteQueue 空闲时照写」，而 cli.ts 那条路、
-- 测试里手搓的连接、以及哪天有人直接 new WriteQueue 都不在那条链上。
-- 判据落在 DDL 上之后，「同一个决定只有最多一张待批卡」是一条**性质**，
-- 不是一条**约定**（0025 把 Hub 的「唯一写入者」从约定变成性质，同一手法）。
--
-- 部分索引（WHERE card_key IS NOT NULL）：不传 card_key 的建卡方【不去重】，
-- 那是显式选择（有些调用方天生没有可复用的身份），它不该被 NULL 的唯一性
-- 语义误伤 —— SQLite 的 UNIQUE 里多个 NULL 【不算】冲突，这恰好是想要的行为，
-- 但把行为建立在「NULL 不冲突」这条三值逻辑上不如直接写出来：
-- 0003 文件头为 events 的 payload 记过同一条教训（「显式写出来是为了让这件事
-- 在 SQL 里【看得见】」）。
--
-- 为什么索引里带 task_id：卡片身份的作用域是【一个任务内的某个决定】，不是全库。
-- 只按 card_key 建会让两个任务里恰好同名的 key 互相挡掉，而 key 的构造法
-- （如 "<taskId>:<gate>:<round>" 由调用方拼）在跨任务时【没有任何全局唯一约束】。
--
-- ── 存量数据 ────────────────────────────────────────────────────────
-- 生产库里 approvals 是【空表】（0013 §10.1），所以这条索引不需要backfill、
-- 也不可能撞存量冲突。测试夹具里那些行是在建表之后插入的，同样不受影响。
--
-- 只用 ALTER TABLE ADD COLUMN + CREATE INDEX，不 DROP / RENAME / ALTER：
-- 与 0002 / 0003 文件头同一条立场 —— 审计库里任何「删掉一个查询路径」的操作
-- 都会让历史回放指向不存在的东西。
-- 不含 PRAGMA：连接级设置归 src/db/pragmas.ts（test/db/migrate.test.ts 有守卫拦这个）。

CREATE UNIQUE INDEX idx_approvals_card_identity
  ON approvals(task_id, card_key) WHERE card_key IS NOT NULL;
